import {spawnSync} from 'node:child_process';
import {existsSync,mkdirSync,copyFileSync,readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import os from 'node:os';
import {createHash} from 'node:crypto';
const root=fileURLToPath(new URL('..',import.meta.url));
const localCargo=path.join(process.env.CARGO_HOME||path.join(os.homedir(),'.cargo'),'bin',process.platform==='win32'?'cargo.exe':'cargo');
const cargo=existsSync(localCargo)?localCargo:'cargo';
const result=spawnSync(cargo,['build','--locked','--release','--target','wasm32-unknown-unknown','-p','warehouse-core'],{cwd:root,stdio:'inherit'});
if(result.error)throw result.error;
if(result.status!==0)process.exit(result.status??1);
const destination=path.join(root,'dist','wasm');mkdirSync(destination,{recursive:true});
const output=path.join(destination,'warehouse_core.wasm');
copyFileSync(path.join(root,'target','wasm32-unknown-unknown','release','warehouse_core.wasm'),output);
const bytes=readFileSync(output),hash=createHash('sha256').update(bytes).digest('hex');
const version=readFileSync(path.join(root,'crates','warehouse-core','Cargo.toml'),'utf8').match(/^version\s*=\s*"([^"]+)"/m)?.[1];
if(!version)throw Error('warehouse-core package version missing');
writeFileSync(path.join(destination,'build.json'),JSON.stringify({crate:'warehouse-core',version,abi:1,rust:'1.100.0',sourceBaseline:'87828aede78b9ff17c5e87c47a364a238caef3f5',sha256:hash,bytes:bytes.length},null,2)+'\n');
console.log(`Rust WebAssembly: ${bytes.length} bytes; sha256 ${hash}`);
